// BuildUserPrompt wraps the incident manifest into the prompt for LLM
func BuildUserPrompt(manifest *normalizer.IncidentManifest) (string, error) {
	manifestJSON, err := json.MarshalIndent(manifest, "", "  ")
	if err != nil {
		return "", fmt.Errorf("ошибка сериализации JSON-манифеста: %w", err)
	}

	var sb strings.Builder
	sb.WriteString("Входной JSON-манифест результатов сканирования целевого хоста:\n```json\n")
	sb.WriteString(string(manifestJSON))
	sb.WriteString("\n```\n\n")
	sb.WriteString(fmt.Sprintf("Целевой узел: %s (ОС: %s). ", manifest.TargetMetadata.IP, manifest.TargetMetadata.OSDetected))
	sb.WriteString("Составь полный структурированный аналитический отчет безопасности строго по указанной форме на русском языке в формате Markdown.")

	return sb.String(), nil
}
